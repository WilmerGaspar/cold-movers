"""Write evidence/VALIDATION_METRICS.md: every detection metric, from the benchmark files, never typed by hand.

Inputs: docs/benchmark_injection.json (development set, 3,300 trials, seed 2026; the neighbour-pull rule was
chosen on it), docs/benchmark_holdout_A.json (pre-registered held-out set A) and, when present,
docs/benchmark_holdout_B.json (held-out set B, new SPHEREx fields). 95 % Wilson intervals.
"""

import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")


def load(name):
    path = os.path.join(DOCS, name)
    return json.load(open(path)) if os.path.exists(path) else None


def wilson(k, n, z=1.96):
    if not n:
        return float("nan"), float("nan")
    p, d = k / n, 1 + z * z / n
    c, h = (p + z * z / (2 * n)) / d, z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def cells(s):
    tp, n, fp = s["confirmed"], s["n"], s["false_confirmed"]
    rl, rh = wilson(tp, n)
    pl, ph = wilson(tp, tp + fp)
    prec = f"{s['precision']:.3f} ({pl:.2f}–{ph:.2f})" if tp + fp else "— (nothing confirmed)"
    distinct = s.get("distinct_false_sources")
    err = f"{100 * s['rate_err_median']:.1f} %" if s["rate_err_median"] == s["rate_err_median"] else "—"
    cand = s.get("candidate_only")
    return (f"{n} | {tp} | {n - tp} | {'—' if cand is None else cand} | {fp}"
            f"{'' if distinct is None else f' ({distinct})'} | {prec} | {s['recall']:.2f} ({rl:.2f}–{rh:.2f}) | "
            f"{s['f1']:.2f} | {err}")


HEAD = ("| Set | Condition | Injections | TP | FN | of which candidates | FP (distinct sources) | Precision | Recall | "
        "F1 | Median speed error |\n|---|---|---|---|---|---|---|---|---|---|---|")


def main():
    dev, a, b = load("benchmark_injection.json"), load("benchmark_holdout_A.json"), load("benchmark_holdout_B.json")
    sets = [("Held-out A", a)] + ([("Held-out B", b)] if b and b.get("trials") else [])
    L = ["# Detection metrics (generated by `scripts/validation_metrics.py`)", "",
         "TP: an injected mover confirmed within 1.5 px of where it was at that detector's first visit. FN: an "
         "injected mover not confirmed (the next column says how many of those were found as candidates). FP: a "
         "confirmed mover that was neither injected nor confirmed before injecting; in brackets, how many distinct "
         "sky positions those false confirmations came from. Precision = TP / (TP + FP); recall = TP / injections; "
         "F1 = 2PR / (P + R). Brackets after precision and recall: 95 % Wilson intervals. Brightness is the "
         "injected peak S/N over the image noise.", "",
         "**Sets.** *Development*: 3,300 trials, seed 2026, fixed speeds (2, 5, 10, 20, 40″/yr) and directions; the "
         "neighbour-pull rule was chosen on it, so its post-fix numbers are optimistic. *Held-out A*: pre-registered "
         "([HOLDOUT_PREREGISTRATION.md](HOLDOUT_PREREGISTRATION.md)), seed 20261115, new spots (quiet, near a star, "
         "crowded) and random motions, same six fields. *Held-out B*: the same design on four SPHEREx fields never "
         "used before, chosen by rule before the run" + ("." if len(sets) > 1 else " (not available when this file was generated)."), ""]
    if a:
        L.append(f"Held-out A: {a['trials']:,} trials, code version {a['app_version']}.")
    if len(sets) > 1:
        fl = ", ".join(f"{k} ({v.get('visits', 0)} visits)" for k, v in b["fields"].items() if "visits" in v)
        miss = ", ".join(f"{k}: {v['skipped']}" for k, v in b["fields"].items() if "skipped" in v)
        L.append(f"Held-out B: {b['trials']:,} trials over {fl}" + (f"; skipped {miss}" if miss else "") + ".")
        for k, why in (b.get("missing_fields") or {}).items():
            L.append(f"Not downloaded, so missing from set B (reported, not replaced): {k} ({why}).")
        if b.get("source"):
            L.append(f"Set B file {b['source']}.")
    L += ["", "## 1. By brightness (all six detectors, speeds 5–20″/yr)", "", HEAD]
    for snr in ("5.0", "8.0", "15.0", "30.0"):
        L.append(f"| Development | S/N {float(snr):g} | {cells(dev['by_snr_core'][snr])} |")
        for name, s in sets:
            L.append(f"| {name} | S/N {float(snr):g} | {cells(s['by_snr_core'][snr])} |")
    L += ["", "### Pre-registered reading", ""]
    for snr in ("8.0", "15.0", "30.0"):
        dp = dev["by_snr_core"][snr]["precision"]
        for name, s in sets:
            h = s["by_snr_core"][snr]
            lo, hi = wilson(h["confirmed"], h["confirmed"] + h["false_confirmed"])
            inside = lo <= dp <= hi
            L.append(f"- S/N {float(snr):g}, {name}: development precision {dp:.3f} is "
                     f"{'inside' if inside else 'outside'} the held-out interval ({lo:.3f}–{hi:.3f})"
                     f"{'' if inside else ': the development figure is optimistic here'}.")
    L += ["", "## 2. By speed (all six detectors, S/N 15)", "", HEAD]
    for k, s in sorted(dev["by_rate_snr15"].items(), key=lambda kv: float(kv[0])):
        L.append(f"| Development | {float(k):g}″/yr | {cells(s)} |")
    for name, s in sets:
        for k in ("2-5", "5-10", "10-20", "20-40"):
            if k in s["by_speed_snr15"]:
                L.append(f"| {name} | {k}″/yr | {cells(s['by_speed_snr15'][k])} |")
    L += ["", "## 3. By environment (all six detectors, speeds 5–20″/yr)", "",
          "Quiet: at least 5 px from any 4σ source. Near a star: 2.5–4 px from a 6σ source. Crowded: at least three "
          "sources within 7 px, none closer than 2.5 px (held-out sets only).", "", HEAD]
    for snr, dq, dn in (("15.0", "by_snr_core_quiet", "by_snr_core_near_star"), ("30.0", "by_snr_core_quiet", "by_snr_core_near_star")):
        L.append(f"| Development | quiet, S/N {float(snr):g} | {cells(dev[dq][snr])} |")
        L.append(f"| Development | near a star, S/N {float(snr):g} | {cells(dev[dn][snr])} |")
        for name, s in sets:
            for place, v in s[f"by_place_snr{int(float(snr))}_core"].items():
                L.append(f"| {name} | {place}, S/N {float(snr):g} | {cells(v)} |")
    L += ["", "## 4. By field (all six detectors, S/N 15, speeds 5–20″/yr)", "", HEAD]
    for k, s in dev["by_field_snr15_core"].items():
        L.append(f"| Development | {k} | {cells(s)} |")
    for name, s in sets:
        for k, v in s["by_field_snr15_core"].items():
            L.append(f"| {name} | {k} | {cells(v)} |")
    L += ["", "## 5. Very red movers (detectors 5 and 6 only, S/N 15, speeds 5–20″/yr)", "", HEAD]
    L.append(f"| Development | all fields | {cells(dev['red_all']['all'])} |")
    for name, s in sets:
        L.append(f"| {name} | all fields | {cells(s['red_D5D6_snr15_core'])} |")
        for k, v in s["red_by_field"].items():
            L.append(f"| {name} | {k} | {cells(v)} |")
    L += ["", "## 6. Every condition together (all six detectors, every speed)", "", HEAD]
    for name, s in sets:
        for snr, v in s["by_snr_all_speeds"].items():
            L.append(f"| {name} | S/N {float(snr):g}, 2–40″/yr | {cells(v)} |")
    L.append("")
    with open(os.path.join(ROOT, "evidence", "VALIDATION_METRICS.md"), "w") as fh:
        fh.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
