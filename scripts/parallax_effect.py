"""How much the yearly parallax of each object biases a straight-line motion fit over its SPHEREx visits.

Cold Movers fits proper motion only (a straight line in time). The real apparent path also contains the
parallax ellipse: SPHEREx orbits the Earth, so it sees each star from a point that circles the Sun once a year.
For each frozen object this script takes its own visit dates and its catalogue parallax, computes the
parallax displacement at each visit, and fits the same kind of straight line to that displacement alone.
The slope is the bias that parallax adds to a motion measured from these visits.

The Sun's position uses the low-precision formula of the Astronomical Almanac (about 0.01°), plenty for
displacements of a fraction of an arcsecond; SPHEREx's orbit around the Earth (about 7,000 km) is ignored.
Writes docs/parallax_effect.md.
"""

import json
import math
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRE = os.path.join(ROOT, "data", "precomputed")
PIXEL_ARCSEC = 6.15


def earth_position_au(mjd):
    """Earth's position relative to the Sun, equatorial J2000-like axes (AU): minus the Sun's geocentric one."""
    n = mjd + 2400000.5 - 2451545.0
    L = math.radians((280.460 + 0.9856474 * n) % 360)
    g = math.radians((357.528 + 0.9856003 * n) % 360)
    lam = L + math.radians(1.915) * math.sin(g) + math.radians(0.020) * math.sin(2 * g)
    eps = math.radians(23.439 - 0.0000004 * n)
    r = 1.00014 - 0.01671 * math.cos(g) - 0.00014 * math.cos(2 * g)
    sun = np.array([r * math.cos(lam), r * math.cos(eps) * math.sin(lam), r * math.sin(eps) * math.sin(lam)])
    return -sun


def parallax_offset_arcsec(ra_deg, dec_deg, plx_mas, mjd):
    """(east, north) apparent displacement in arcsec caused by parallax at a date."""
    a, d = math.radians(ra_deg), math.radians(dec_deg)
    x, y, z = earth_position_au(mjd)
    p = plx_mas / 1000.0
    east = p * (x * math.sin(a) - y * math.cos(a))
    north = p * (x * math.sin(d) * math.cos(a) + y * math.sin(d) * math.sin(a) - z * math.cos(d))
    return east, north


def main():
    lines = ["# Parallax bias of the straight-line motion fit (generated by `scripts/parallax_effect.py`)", "",
             "Cold Movers fits a straight line (proper motion only) to positions measured at each SPHEREx visit. "
             "Parallax adds a yearly ellipse to the real path. This table fits the same straight line to the "
             "parallax displacement alone, at each object's own visit dates, so the slope is the bias parallax "
             "adds to the measured motion. Catalogue parallaxes; the Sun's position from the Astronomical "
             "Almanac's low-precision formula.", "",
             "| Object | Parallax | Visits (span) | Largest parallax shift between visits | Bias on the fitted motion | "
             "Bias in pixels per year | Compared with the measured − catalogue difference |",
             "|---|---|---|---|---|---|---|"]
    records = {}
    rec_path = os.path.join(ROOT, "docs", "validation_records.csv")
    import csv
    recs = {r["key"]: r for r in csv.DictReader(open(rec_path))} if os.path.exists(rec_path) else {}
    for key in sorted(os.listdir(PRE)):
        path = os.path.join(PRE, key, "result.json")
        if not os.path.exists(path):
            continue
        res = json.load(open(path))
        t = res["target"]
        plx = t.get("parallax_mas")
        mjds = np.array([e["mjd_mid"] for e in res["epochs"]])
        if not plx or len(mjds) < 2:
            continue
        off = np.array([parallax_offset_arcsec(t["ra_deg"], t["dec_deg"], plx, m) for m in mjds])
        off -= off[0]
        yrs = (mjds - mjds[0]) / 365.25
        ve = np.polyfit(yrs, off[:, 0], 1)[0]
        vn = np.polyfit(yrs, off[:, 1], 1)[0]
        bias = math.hypot(ve, vn)
        jump = max(math.hypot(*(off[i] - off[j])) for i in range(len(off)) for j in range(len(off)))
        r = recs.get(key, {})
        cat = float(r["catalogue_motion_arcsec_yr"]) if r.get("catalogue_motion_arcsec_yr") else None
        fit = float(r["trajectory_motion_arcsec_yr"]) if r.get("trajectory_motion_arcsec_yr") else None
        err = float(r["trajectory_err_arcsec_yr"]) if r.get("trajectory_err_arcsec_yr") else None
        comp = (f"fitted {fit:.2f} ± {err:.2f} vs catalogue {cat:.2f}″/yr: difference {fit - cat:+.2f}″/yr"
                if fit is not None and cat is not None else "no trajectory fit (slower than 0.5″/yr)")
        records[key] = {"parallax_mas": plx, "visits": len(mjds), "span_yr": round(float(yrs[-1]), 3),
                        "max_shift_arcsec": round(jump, 3), "bias_arcsec_yr": round(bias, 3),
                        "bias_east_north": [round(ve, 3), round(vn, 3)]}
        lines.append(f"| {t.get('name', key)} | {plx:.1f} mas | {len(mjds)} ({yrs[-1]:.2f} yr) | {jump:.2f}″ "
                     f"({jump / PIXEL_ARCSEC:.2f} px) | {bias:.2f}″/yr | {bias / PIXEL_ARCSEC:.3f} | {comp} |")
    lines += ["", "Reading: when the bias is comparable with the measurement uncertainty, the straight-line "
              "motion of that object should not be over-interpreted; modelling parallax needs more visits spread "
              "over the year (SPHEREx returns about every six months, so most objects have 3-6 visits).", ""]
    with open(os.path.join(ROOT, "docs", "parallax_effect.md"), "w") as fh:
        fh.write("\n".join(lines))
    with open(os.path.join(ROOT, "docs", "parallax_effect.json"), "w") as fh:
        json.dump(records, fh, indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
