"""Write the evidence ledger and keep the README and final report summaries identical to it.

Outputs: docs/evidence_ledger.json, evidence/EVIDENCE_LEDGER.md, and the block between
<!-- evidence-summary:start --> and <!-- evidence-summary:end --> in README.md and
evidence/FINAL_VALIDATION_REPORT.md. Usage: python scripts/evidence_report.py [--check]
With --check nothing is written; the exit code is 1 if any file is out of date.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from coldmovers import evidence  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHECK = "--check" in sys.argv


def write(path, text):
    full = os.path.join(ROOT, path)
    old = open(full).read() if os.path.exists(full) else None
    if old == text:
        return True
    if CHECK:
        print(f"out of date: {path}")
        return False
    with open(full, "w") as fh:
        fh.write(text)
    print(f"wrote {path}")
    return True


def with_block(path, block):
    full = os.path.join(ROOT, path)
    text = open(full).read()
    a, b = text.index(evidence.MARK_START), text.index(evidence.MARK_END)
    return text[:a + len(evidence.MARK_START)] + "\n" + block + "\n" + text[b:]


ledger = evidence.build_ledger(ROOT)
summary = evidence.summary_markdown(ledger)
doc = "\n".join([
    "# Evidence ledger (generated by `scripts/evidence_report.py`)", "",
    "Every important result of Cold Movers, with the kind of evidence it is. A = real SPHEREx measurement; "
    "B = injection-recovery test (artificial movers added to copies of real images); C = candidate, not confirmed; "
    "D = inconclusive or not detected; S = synthetic or computed check. Catalogue and published values appear only "
    "as external comparisons. Built from the files in each row's last column; nothing is typed by hand.", "",
    "## Summary", "", summary, "", "## Every result", "",
    evidence.traceability_markdown(ledger), "",
    "## Details (source, method, uncertainty, limitations)", ""]
    + [f"- **{e['claim']}** ({e['category']} · {e['status']}). Source: {e['source']}. Method: {e['method']}. "
       f"Uncertainty: {e['uncertainty']}. Limitations: {e['limitations'] or 'none noted'}." for e in ledger] + [""])
ok = write("docs/evidence_ledger.json", json.dumps(ledger, indent=1, ensure_ascii=False) + "\n")
ok &= write("evidence/EVIDENCE_LEDGER.md", doc)
for path in ("README.md", "evidence/FINAL_VALIDATION_REPORT.md"):
    ok &= write(path, with_block(path, summary))
sys.exit(0 if ok else 1)
