"""Build the validation scoreboard with the app's own code on the frozen results (runs on GitHub Actions).

Writes data/scoreboard.json (read by the app) and docs/scoreboard.md (quoted in the README).
"""

import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np  # noqa: E402

from coldmovers import __version__, checks, movers, pipeline, scoreboard, validation, variability  # noqa: E402
from coldmovers.references import PUBLISHED  # noqa: E402
from coldmovers.targets import Target  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRE = os.path.join(ROOT, "data", "precomputed")

vrows = {v["key"]: v for v in validation.validate(PRE)}
fields, verdicts, confirmed_elsewhere = {}, {}, {}
for key in vrows:
    outdir = os.path.join(PRE, key)
    view = pipeline.load(outdir)
    stacks = validation.load_stacks(outdir)
    target = Target.from_dict(view["target"])
    marker = validation.marker_for(target, view["ref_wcs"])
    rows = view["rows"]
    checks.mark_blends(rows, view["epochs"], stacks, marker)
    verdicts[key] = variability.light_curve(rows, view["epochs"])["verdict"]
    found = movers.search_all(view["epochs"], stacks)
    x0, y0 = marker(min(ep["mjd_mid"] for ep in view["epochs"]))
    confirmed_elsewhere[key] = sum(c["confirmed"] and np.hypot(c["x"] - x0, c["y"] - y0) > 2.0
                                   for c in found["candidates"])
    fields[key] = (view["epochs"], stacks)
for key, v in vrows.items():
    pub = PUBLISHED.get(key, {})
    v["published_range_k"] = (pub.get("low_k"), pub.get("high_k"))

rows = [
    scoreboard.motion_control(vrows["barnard"]),
    scoreboard.motion_control(vrows["epsindib"]),
    scoreboard.motion_control(vrows["wise0855"]),
    scoreboard.track_control(list(vrows.values())),
    scoreboard.temperature_control(vrows["trappist1"]),
    scoreboard.temperature_control(vrows["epsindib"]),
    scoreboard.variability_control("R Draconis", verdicts["rdra"]),
    scoreboard.variability_control("RW Aurigae", verdicts["rwaur"]),
    scoreboard.still_control(vrows["rdra"], confirmed_elsewhere["rdra"]),
    scoreboard.still_control(vrows["rwaur"], confirmed_elsewhere["rwaur"]),
    scoreboard.refusal_control(vrows["barnard"], "saturates the detector"),
    scoreboard.refusal_control(vrows["wise0855"], "too cold for SPHEREx to see its peak"),
    scoreboard.synthetic_temperatures(),
    scoreboard.series_bound_check(),
]
inj_rows, inj_details = scoreboard.injection_campaign(fields)
rows += inj_rows
total_elsewhere = sum(confirmed_elsewhere.values())
rows.insert(10, scoreboard.row(
    "Negative control · motion", "No unexplained confirmed movers in the six fields",
    "pass" if total_elsewhere == 0 else "partial",
    f"{total_elsewhere} confirmed movers besides the targets (" +
    ", ".join(f"{k} {n}" for k, n in confirmed_elsewhere.items()) + ")",
    "pass: no confirmed mover other than the known target; partial: some (they must then be checked one by one)"))

out = {"generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"), "app_version": __version__,
       "counts": scoreboard.counts(rows), "rows": rows, "injection": inj_details}
with open(os.path.join(ROOT, "data", "scoreboard.json"), "w") as fh:
    json.dump(out, fh, indent=2, ensure_ascii=False)

icon = {"pass": "🟢 pass", "partial": "🟡 partial", "fail": "🔴 fail"}
c = out["counts"]
lines = [f"# Validation scoreboard: {c['pass']} pass · {c['partial']} partial · {c['fail']} fail",
         "",
         f"Generated by `scripts/scoreboard.py` with the app's own code (version {__version__}) on the frozen "
         "results. Pass rules are fixed in `coldmovers/scoreboard.py`; every result is shown.",
         "",
         "| Category | Check | Result | Status | Rule |", "|---|---|---|---|---|"]
for r in rows:
    lines.append(f"| {r['category']} | {r['check']} | {r['result']} | {icon[r['status']]} | {r['rule']} |")
notes = [r for r in rows if r.get("note")]
if notes:
    lines += [""] + [f"**{r['check']}.** {r['note']}" for r in notes]
lines += ["", f"Injected movers: {inj_details['note']} Fields used: {', '.join(inj_details['fields_used'])}."]
with open(os.path.join(ROOT, "docs", "scoreboard.md"), "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("\n".join(lines))
