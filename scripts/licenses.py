"""Write docs/licenses.md: the licence of every installed package, read from its own metadata.

Runs on GitHub Actions after `pip install -r requirements.txt pytest playwright`, so the table
describes exactly the packages the app and its tests use. Nothing is typed by hand: each licence
comes from the package's License-Expression, its "License ::" classifiers, or the first line of its
License field, in that order. Any licence containing GPL is listed separately for review.
"""

import importlib.metadata as md
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRA = ("pytest", "playwright")  # used only by the tests and the screenshot robot


def canon(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def licence_of(dist):
    meta = dist.metadata
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr, "License-Expression"
    cls = [c.split("::")[-1].strip() for c in (meta.get_all("Classifier") or []) if c.startswith("License ::")]
    if cls:
        return "; ".join(cls), "classifier"
    text = (meta.get("License") or "").strip()
    if text:
        return text.splitlines()[0][:80], "License field (first line)"
    return "not stated in metadata", "-"


with open(os.path.join(ROOT, "requirements.txt")) as fh:
    direct = [canon(ln.split("==")[0]) for ln in fh if ln.strip() and not ln.startswith("#")]
wanted = direct + [canon(e) for e in EXTRA]

rows = {}
for dist in md.distributions():
    name = dist.metadata.get("Name")
    if name:
        rows[canon(name)] = (name, dist.version, *licence_of(dist))

lines = [
    "# Licences of the packages Cold Movers uses (generated by `scripts/licenses.py` on GitHub Actions)",
    "",
    f"Python {sys.version.split()[0]}. Each licence is read from the installed package's own metadata, "
    "not typed by hand. Cold Movers' own code is MIT (see LICENSE).",
    "",
    "## Direct dependencies (requirements.txt) and test tools",
    "",
    "| Package | Version | Licence | Read from |",
    "|---|---|---|---|",
]
for key in wanted:
    if key in rows:
        name, ver, lic, src = rows[key]
        lines.append(f"| {name} | {ver} | {lic} | {src} |")
    else:
        lines.append(f"| {key} | not installed in this run | - | - |")
others = sorted(k for k in rows if k not in wanted)
lines += ["", "## Everything else installed with them", "", "| Package | Version | Licence |", "|---|---|---|"]
lines += [f"| {rows[k][0]} | {rows[k][1]} | {rows[k][2]} |" for k in others]
gpl = [rows[k] for k in rows if "GPL" in rows[k][2].upper()]
lines += ["", "## Copyleft check", ""]
if gpl:
    lines.append("Packages whose metadata mentions GPL (to review; none of their code is copied into Cold Movers):")
    lines += [f"- {n} {v}: {lic}" for n, v, lic, _ in gpl]
else:
    lines.append("No installed package declares a GPL-family licence in its metadata.")
lines.append("")
os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
with open(os.path.join(ROOT, "docs", "licenses.md"), "w") as fh:
    fh.write("\n".join(lines))
print("\n".join(lines))
