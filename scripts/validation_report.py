"""Write docs/validation.md with the app's own validation numbers (runs on GitHub Actions).

Uses exactly the code the app uses (coldmovers.validation) on the frozen results, so the
README can quote the same numbers a judge sees in the app.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from coldmovers import madhava, validation  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIGHT = {"green": "🟢", "yellow": "🟡", "red": "🔴"}

rows = validation.validate(os.path.join(ROOT, "data", "precomputed"))
lines = [
    "# Validation numbers (generated by `scripts/validation_report.py` with the app's own code)",
    "",
    "| Object | SPHEREx images / visits | Moved between first and last visit (measured / catalogue) "
    "| Found with no catalogue | Catalogue motion | Blackbody-equivalent temperature | Published |",
    "|---|---|---|---|---|---|---|",
]
for v in rows:
    moved = (f"{v['moved_measured']:.1f}″ / {v['moved_predicted']:.1f}″"
             if v["moved_measured"] is not None else "—")
    free = (f"{v['free_rate']:.2f}″/yr towards {v['free_pa']:.0f}°, {v['free_status']} "
            f"(detector{'s' if len(v['free_detectors']) > 1 else ''} {', '.join(map(str, v['free_detectors']))})"
            if v.get("free_rate") else "none")
    temp = (f"{LIGHT[v['light']]} {v['temperature']:,.0f} K" if v["temperature"] and v["light"] != "red"
            else f"{LIGHT[v['light']]} not reliable")
    why = "; ".join(madhava.REASON_TEXT.get(r, r).split(":")[0].split(".")[0] for r in v["reasons"])
    name = v["name"] + (" *(extra)*" if v.get("extra") else "")
    lines.append(f"| {name} | {v['images']} / {v['visits']} | {moved} | {free} | "
                 f"{v['catalogue_rate']:.2f}″/yr, {v['catalogue_pa']:.0f}° | {temp}: {why} | {v['published']} |")
os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
with open(os.path.join(ROOT, "docs", "validation.md"), "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("\n".join(lines))

# ------------------------------------------------------------------ evidence records
import csv  # noqa: E402

from coldmovers import __version__  # noqa: E402


def fmt(x, nd=2):
    return "" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


records = []
for v in rows:
    tr = v.get("trajectory") or {}
    br = v.get("brightness") or {}
    rec = {
        "object": v["name"], "key": v["key"], "code_version": __version__,
        "data": "SPHEREx DR1 + QR3 (NASA/IPAC IRSA); one IRSA cutout URL per image in data/precomputed/"
                f"{v['key']}/photometry.csv",
        "spherex_files": v["n_files"], "images_used": v["images"], "visits": v["visits"],
        "first_visit": v["first_date"], "last_visit": v["last_date"],
        "detectors": " ".join(map(str, v["detectors_used"])),
        "catalogue_motion_arcsec_yr": fmt(v["catalogue_rate"]), "catalogue_pa_deg": fmt(v["catalogue_pa"], 0),
        "blind_motion_arcsec_yr": fmt(v["free_rate"]), "blind_motion_err_arcsec_yr": fmt(v["free_rate_err"]),
        "blind_pa_deg": fmt(v["free_pa"], 0), "blind_status": v["free_status"] or "none",
        "blind_detectors": " ".join(map(str, v["free_detectors"])),
        "blind_minus_catalogue_sigma": fmt((v["free_rate"] - v["catalogue_rate"]) / v["free_rate_err"])
        if v["free_rate"] and v["free_rate_err"] else "",
        "trajectory_motion_arcsec_yr": fmt(tr.get("rate")), "trajectory_err_arcsec_yr": fmt(tr.get("rate_err")),
        "trajectory_pa_deg": fmt(tr.get("pa"), 0), "trajectory_chi2_red": fmt(tr.get("chi2_red")),
        "trajectory_minus_catalogue_sigma": fmt((tr["rate"] - tr["catalogue_rate"]) / tr["rate_err"])
        if tr.get("rate_err") else "",
        "bb_equivalent_temperature_k": fmt(v["temperature"], 0), "temperature_range_k":
            f"{v['t_low']:.0f}-{v['t_high']:.0f}" if v["t_low"] and v["t_high"] else "",
        "traffic_light": v["light"], "published_temperature": v["published"],
        "brightness_change_mag": fmt(br.get("amplitude_mag")), "brightness_change_sigma": fmt(br.get("significance"), 1),
        "checks": "; ".join(f"{k}: {s}" for k, s in v["checks"].items()),
        "trusted_detectors": v["reliable_detectors"], "span_years": fmt(v["span_years"]),
        "motion_verdict": v["motion_verdict"], "motion_verdict_why": v["motion_verdict_why"],
        "temperature_verdict": v["temperature_verdict"], "temperature_verdict_why": v["temperature_verdict_why"],
    }
    records.append(rec)
with open(os.path.join(ROOT, "docs", "validation_records.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(records[0]))
    w.writeheader()
    w.writerows(records)
md = ["# Evidence records (generated by `scripts/validation_report.py` with the app's own code)", "",
      f"Code version {__version__}. One row per object; the CSV next to this file has every field. Blind motion = "
      "catalogue-free search (no position or motion given); its uncertainty is approximated as rate / significance. "
      "Trajectory = straight-line fit to positions measured near the predicted track (catalogue-assisted). "
      "Verdicts (rules in `coldmovers/validation.py`): CONFIRMED only when the catalogue-free search sees the same "
      "motion in two or more trusted detectors with a combined significance of 5 or more; CANDIDATE when the evidence "
      "is weaker; INCONCLUSIVE when fewer than two detectors can be trusted; NOT DETECTED when trusted detectors "
      "show no motion. A temperature is INCONCLUSIVE on a red light.", "",
      "| Object | Motion verdict | Temperature verdict | Files / visits / detectors | Blind motion (status) | Trajectory "
      "| Catalogue | Temperature (light) | Published | Brightness change |", "|---|---|---|---|---|---|---|---|---|---|"]
for r in records:
    blind = (f"{r['blind_motion_arcsec_yr']} ± {r['blind_motion_err_arcsec_yr']}″/yr, {r['blind_pa_deg']}° "
             f"({r['blind_status']}, {', '.join('D' + d for d in r['blind_detectors'].split())}; "
             f"{r['blind_minus_catalogue_sigma']}σ)"
             if r["blind_motion_arcsec_yr"] else "none")
    traj = (f"{r['trajectory_motion_arcsec_yr']} ± {r['trajectory_err_arcsec_yr']}″/yr, {r['trajectory_pa_deg']}°, "
            f"χ²r {r['trajectory_chi2_red']} ({r['trajectory_minus_catalogue_sigma']}σ)"
            if r["trajectory_motion_arcsec_yr"] else "slower than 0.5″/yr: not fitted")
    md.append(f"| {r['object']} | **{r['motion_verdict']}**: {r['motion_verdict_why']} | "
              f"**{r['temperature_verdict']}** | {r['spherex_files']} / {r['visits']} / {r['detectors']} | {blind} | {traj} | "
              f"{r['catalogue_motion_arcsec_yr']}″/yr, {r['catalogue_pa_deg']}° | "
              f"{(r['bb_equivalent_temperature_k'] + ' K') if r['bb_equivalent_temperature_k'] else 'not reliable'}"
              f" ({r['traffic_light']}) | {r['published_temperature']} | {r['brightness_change_mag']} mag, "
              f"{r['brightness_change_sigma']}σ |")
with open(os.path.join(ROOT, "docs", "validation_records.md"), "w") as fh:
    fh.write("\n".join(md) + "\n")
print("\n".join(md))
