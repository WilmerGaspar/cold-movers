"""Write evidence/BENCHMARK_TABLES.md from docs/benchmark_injection_before.json and docs/benchmark_injection.json."""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = json.load(open(os.path.join(ROOT, "docs", "benchmark_injection_before.json")))
A = json.load(open(os.path.join(ROOT, "docs", "benchmark_injection.json")))
TITLES = {
    "by_snr_core": "All fields, quiet and near-star spots, speeds 5-20″/yr, all six detectors, by S/N",
    "by_snr_core_quiet": "Quiet spots (≥5 px from any source at the first visit), speeds 5-20″/yr, by S/N",
    "by_snr_core_near_star": "Spots 2.5-4 px from a star, speeds 5-20″/yr, by S/N",
    "by_rate_snr15": "S/N 15, all spots and fields, by speed (″/yr)",
    "by_field_snr15_core": "S/N 15, speeds 5-20″/yr, by field",
    "red_by_field": "Very red movers (only D5 and D6), S/N 15, speeds 5-20″/yr, by field",
}


def cell(s):
    p = "—" if s["precision"] != s["precision"] else f"{s['precision']:.3f}"
    e = "—" if s["rate_err_median"] != s["rate_err_median"] else f"{100 * s['rate_err_median']:.1f} %"
    return f"{s['confirmed']} | {s['false_confirmed']} | {s['recall']:.2f} | {p} | {s['f1']:.2f} | {e}"


lines = ["# Blind injection benchmark: tables (generated by `scripts/benchmark_report.py`)", "",
         f"Before: code at commit ef5d02a (v0.4.9). After: neighbour-pull rule (this branch). Same {A['trials']} trials, "
         "same random seed, same spots. TP = injected movers recovered as confirmed; FP = confirmed movers that are "
         "neither the injection nor present before injecting; recall = TP / n; precision = TP / (TP + FP); "
         "rate error = median absolute relative error of the recovered speed.", ""]
for sec, title in TITLES.items():
    lines += [f"## {title}", "", "| Group | n | Before: TP | FP | Recall | Precision | F1 | Rate error | "
              "After: TP | FP | Recall | Precision | F1 | Rate error |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in B[sec]:
        lines.append(f"| {k} | {B[sec][k]['n']} | {cell(B[sec][k])} | {cell(A[sec][k])} |")
    lines.append("")
lines += ["## Fields", "", "| Field | Detectors whose alignment is trusted (of 6) | Confirmed movers before injecting | Visits |",
          "|---|---|---|---|"]
for k, f in A["fields"].items():
    lines.append(f"| {k} | {f['reliable_detectors']} | {f['baseline_confirmed']} | {f['visits']} |")
os.makedirs(os.path.join(ROOT, "evidence"), exist_ok=True)
open(os.path.join(ROOT, "evidence", "BENCHMARK_TABLES.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[:40]))
